export function getSaasAlternatives(validIds) {
  const ok = validIds ? new Set(validIds) : null;
  return SAAS
    .map((s) => ({ ...s, packs: ok ? s.packs.filter((id) => ok.has(id)) : s.packs }))
    .filter((s) => s.packs.length > 0)
    .sort((a, b) => a.name.localeCompare(b.name));
}
